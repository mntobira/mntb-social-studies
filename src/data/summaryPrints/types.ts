/**
 * ===================================================================
 * 磯和プリント方式 × 1画面ページ送り式 まとめプリント 型定義
 * （マナトビリスニング第6問B準拠：1画面図表カルーセル・タップ○×メモ対応）
 * ===================================================================
 * 記法ルール（本文・表セル・Point枠内で共通利用可能）:
 *  1. {{重要語句}}          : 【下線＋太字】共通テスト8割突破の必須重要語句（赤シート標準マスク対象）
 *  2. [[マイナー語句]]      : 【下線】共通テスト9割〜満点狙いのハイレベル語句（満点モード時にマスク対象）
 *  3. ~~波線（**太字**）~~  : 【波線＋導出語太字】共通テストで問われる思想内容・因果の急所（赤シート時も文脈ヒントとして表示）
 */
import type { SubjectKey } from '../subjects';

export interface PrintOxItem {
  /** ○×確認問題文 */
  q: string;
  /** 正解（○ または ×） */
  a: '○' | '×';
  /** ○の根拠確認、または ×の誤り箇所指摘（例: × 短い → ◎ 長い） */
  why: string;
}

/**
 * マナトビリスニング第6問B準拠の視覚資料（グラフ・地図・概念図）
 * - 1枚のとき：FitFigure で枠のアスペクト比に合わせて1面に収め、タップで ○／× メモ＋全画面拡大が可能
 * - 複数枚のとき：FigureCarousel（‹ › 44pxボタン＋①〜④タブ＋スワイプ）で1枚ずつ大きく切り替え可能
 */
export interface PrintFigure {
  /** public 配下の SVG / PNG パス（例: "/social_figs/q6b_ge_power_1.svg"） */
  src: string;
  /** 図版キャプション（例: "① 水力発電が約9割を占める国（ノルウェー）"） */
  caption: string;
  /** 左上バッジ・カルーセル番号ラベル（例: "①" / "資料1"） */
  badge?: string;
  /** 資料判読の着眼点ワンポイント（任意） */
  note?: string;
}

export interface PrintFlowBlock {
  /** ブロック見出し（人物・テーマ・段階など） */
  heading: string;
  /** 右肩の小ラベル（例: 「因果の流れ」「対比の急所」「背景→展開」） */
  badge?: string;
  /**
   * 流れを作るステップ行。先頭記号に応じて視覚的に整形される:
   * - 「Ｑ」「【問い】」「【背景】」: 問いかけ・時代背景ラベル
   * - 「→」「⇒」                  : 因果の展開・噛み砕き・具体例
   * - 「＝」                        : 結論・定義の集約
   * - 「↔」「⇔」「※」             : 対比・共通テストひっかけ注意
   */
  lines: string[];
}

export interface SummaryPrintPage {
  /** このページの1画面タイトル */
  pageTitle: string;
  /** 共通テスト頻出度（3〜5） */
  priority: 3 | 4 | 5;
  /** 冒頭でページ全体の流れ（ストーリー）を掴む1〜2文の導入 */
  lead?: string;
  /**
   * マナトビリスニング第6問B準拠の図版・グラフ資料（任意）
   * ページ内に図版がある場合、「要点ノート / 図表資料（○×メモ）」の1画面タブまたは2カラムで
   * 縦スクロールを増やさず1画面いっぱいに表示・比較できる。
   */
  figures?: PrintFigure[];
  /** 図表資料の上部に並べる1行比較○×メモ項目（例: ["① ノルウェー", "② フランス", "③ ドイツ", "④ 日本"]） */
  figureMemoItems?: string[];
  /** 論理フローブロック（表メインのページでは省略可） */
  blocks?: PrintFlowBlock[];
  /** 比較・整理テーブル（任意） */
  table?: {
    headers: string[];
    rows: string[][];
  };
  /** 枠囲みの共通テスト急所・混同注意ポイント（任意） */
  pointBox?: {
    title: string;
    body: string;
  };
  /** 磯和式「×の理由を指摘できるまで」即答○×チェック（任意） */
  oxChecks?: PrintOxItem[];
}

export interface SummaryPrintSheet {
  id: string;
  subject: SubjectKey;
  /** 編タイトル（目次でのグルーピング用） */
  partTitle: string;
  /** 単元番号ラベル（例: "単元01"） */
  unitLabel: string;
  /** 対応する演習チャプターID（「この単元を演習する」ボタン用） */
  chapterId: string;
  /** 単元タイトル */
  title: string;
  /** 単元サブタイトル（網羅範囲の要約） */
  subtitle: string;
  /** 1画面ごとにめくれるページ配列 */
  pages: SummaryPrintPage[];
}
